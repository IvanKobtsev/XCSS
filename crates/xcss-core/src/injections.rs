fn dimension_unit(value: &str) -> Option<&str> {
    let at = value
        .char_indices()
        .find(|(_, c)| !matches!(c, '0'..='9' | '+' | '-' | '.' | 'e' | 'E'))
        .map(|(at, _)| at)?;
    value[..at].parse::<f64>().ok()?;
    Some(&value[at..])
}

fn is_dynamic(value: &str) -> bool {
    value.contains('$') || value.contains("#{") || value.contains("var(") || value.contains("calc(")
}
fn canonical(name: &str) -> String {
    name.replace('_', "-").to_ascii_lowercase()
}
fn is_ident_byte(byte: u8) -> bool {
    byte.is_ascii_alphanumeric() || matches!(byte, b'-' | b'_')
}
fn starts_comment(bytes: &[u8], index: usize) -> bool {
    bytes.get(index) == Some(&b'/') && bytes.get(index + 1) == Some(&b'*')
}
fn skip_ws(bytes: &[u8], mut index: usize) -> usize {
    while index < bytes.len() && bytes[index].is_ascii_whitespace() {
        index += 1;
    }
    index
}
fn skip_comment(bytes: &[u8], mut index: usize) -> usize {
    index += 2;
    while index + 1 < bytes.len() {
        if bytes[index] == b'*' && bytes[index + 1] == b'/' {
            return index + 2;
        }
        index += 1;
    }
    bytes.len()
}
fn skip_string(bytes: &[u8], start: usize) -> usize {
    let quote = bytes[start];
    let mut index = start + 1;
    while index < bytes.len() {
        if bytes[index] == b'\\' {
            index += 2;
        } else if bytes[index] == quote {
            return index + 1;
        } else {
            index += 1;
        }
    }
    bytes.len()
}
fn utf8_len(byte: u8) -> usize {
    match byte {
        0..=0x7f => 1,
        0xc0..=0xdf => 2,
        0xe0..=0xef => 3,
        _ => 4,
    }
}

fn matching(source: &str, open: usize, left: u8, right: u8) -> Option<usize> {
    let bytes = source.as_bytes();
    let mut depth = 1usize;
    let mut index = open + 1;
    while index < bytes.len() {
        if starts_comment(bytes, index) {
            index = skip_comment(bytes, index);
            continue;
        }
        if matches!(bytes[index], b'\'' | b'"') {
            index = skip_string(bytes, index);
            continue;
        }
        if bytes[index] == left {
            depth += 1;
        } else if bytes[index] == right {
            depth -= 1;
            if depth == 0 {
                return Some(index);
            }
        }
        index += 1;
    }
    None
}

fn split_top_level(source: &str, delimiter: u8) -> Vec<&str> {
    let bytes = source.as_bytes();
    let mut parts = Vec::new();
    let mut start = 0;
    let mut index = 0;
    let mut depth = 0usize;
    while index < bytes.len() {
        if matches!(bytes[index], b'\'' | b'"') {
            index = skip_string(bytes, index);
            continue;
        }
        match bytes[index] {
            b'(' | b'[' | b'{' => depth += 1,
            b')' | b']' | b'}' => depth = depth.saturating_sub(1),
            value if value == delimiter && depth == 0 => {
                parts.push(&source[start..index]);
                start = index + 1;
            }
            _ => {}
        }
        index += 1;
    }
    parts.push(&source[start..]);
    parts
}
fn top_level_equals(source: &str) -> Option<usize> {
    let bytes = source.as_bytes();
    let mut depth = 0usize;
    for (index, byte) in bytes.iter().copied().enumerate() {
        match byte {
            b'(' | b'[' => depth += 1,
            b')' | b']' => depth = depth.saturating_sub(1),
            b'=' if depth == 0 => return Some(index),
            _ => {}
        }
    }
    None
}

fn remove_spans(source: &str, spans: &[SourceSpan]) -> String {
    let mut output = source.to_owned();
    let mut spans = spans.to_vec();
    spans.sort_by_key(|span| std::cmp::Reverse(span.start));
    for span in spans {
        output.replace_range(span.start..span.end, "");
    }
    output
}
fn line_column(source: &str, offset: usize) -> (usize, usize) {
    let prefix = &source[..offset.min(source.len())];
    let line = prefix.bytes().filter(|byte| *byte == b'\n').count() + 1;
    let start = prefix.rfind('\n').map_or(0, |index| index + 1);
    (line, prefix[start..].chars().count() + 1)
}
fn diagnostic(file: &ParsedFile, span: SourceSpan, message: &str) -> Diagnostic {
    file_diagnostic_raw(&file.filename, &file.source, span.start, span.end, message)
}
fn file_diagnostic(file: &ProjectFile<'_>, start: usize, end: usize, message: &str) -> Diagnostic {
    file_diagnostic_raw(file.filename, file.source, start, end, message)
}
fn file_diagnostic_raw(
    filename: &str,
    source: &str,
    start: usize,
    end: usize,
    message: &str,
) -> Diagnostic {
    let (line, column) = line_column(source, start);
    Diagnostic {
        message: message.into(),
        severity: Severity::Error,
        span: SourceSpan { start, end },
        line,
        column,
        filename: Some(filename.into()),
    }
}
fn plain_diagnostic(filename: Option<&str>, message: &str) -> Diagnostic {
    Diagnostic {
        message: message.into(),
        severity: Severity::Error,
        span: SourceSpan { start: 0, end: 0 },
        line: 1,
        column: 1,
        filename: filename.map(str::to_owned),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn file<'a>(module_id: &'a str, source: &'a str) -> ProjectFile<'a> {
        ProjectFile {
            module_id,
            filename: module_id,
            source,
        }
    }

    #[test]
    fn extracts_definitions_and_rewrites_calls_and_content() {
        let source = "@injection underline($size: length = 1px) { border-width: $size; @content; }\n.a { @:underline(2px) { color: red; } }";
        let output = compile_project(
            &[file("a.xcss", source)],
            &[],
            "a.xcss",
            "/tmp/_injections.scss",
        )
        .unwrap();
        assert!(output.partial.contains("@mixin xcss-"));
        assert!(output.partial.contains("$size: 1px"));
        assert!(output.code.contains("@include xcss-"));
        assert!(!output.code.contains("@injection"));
    }

    #[test]
    fn resolves_unique_local_named_and_namespace_injections() {
        let library = file(
            "tokens.xcss",
            "@injection tone($color: color) { color: $color; }",
        );
        let consumer_source = "@import lib from \"./tokens.xcss\"; .a { @:lib.tone(red); }";
        let consumer = file("consumer.xcss", consumer_source);
        let resolution = ImportResolution {
            importer: "consumer.xcss",
            specifier: "./tokens.xcss",
            target: "tokens.xcss",
        };
        let output = compile_project(
            &[library, consumer],
            &[resolution],
            "consumer.xcss",
            "/tmp/_injections.scss",
        )
        .unwrap();
        assert!(output.code.contains("@include xcss-"));
        assert!(!output.code.contains("@import"));
    }

    #[test]
    fn rejects_ambiguous_names_collisions_and_literal_mismatches() {
        let duplicate = compile_project(
            &[file(
                "a.xcss",
                "@injection foo-bar {} @injection foo_bar {}",
            )],
            &[],
            "a.xcss",
            "/tmp/_injections.scss",
        )
        .unwrap_err();
        assert!(
            duplicate
                .iter()
                .any(|error| error.message.contains("duplicate"))
        );

        let mismatch = compile_project(
            &[file(
                "a.xcss",
                "@injection angle($value: angle) {} .a { @:angle(2px); }",
            )],
            &[],
            "a.xcss",
            "/tmp/_injections.scss",
        )
        .unwrap_err();
        assert!(
            mismatch
                .iter()
                .any(|error| error.message.contains("does not match"))
        );

        let ambiguous = compile_project(
            &[
                file("a.xcss", "@injection shared {}"),
                file("b.xcss", "@injection shared {}"),
                file("c.xcss", ".c { @:shared; }"),
            ],
            &[],
            "c.xcss",
            "/tmp/_injections.scss",
        )
        .unwrap_err();
        assert!(
            ambiguous
                .iter()
                .any(|error| error.message.contains("ambiguous"))
        );
    }
}
