use std::collections::{BTreeMap, BTreeSet};

use crate::{Diagnostic, Severity, SourceSpan, Syntax, TransformOptions, fnv1a64, transform};

#[derive(Clone, Debug)]
pub struct ProjectFile<'a> {
    pub module_id: &'a str,
    pub filename: &'a str,
    pub source: &'a str,
}

#[derive(Clone, Debug)]
pub struct ImportResolution<'a> {
    pub importer: &'a str,
    pub specifier: &'a str,
    pub target: &'a str,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ProjectOutput {
    pub code: String,
    pub partial: String,
}

#[derive(Clone, Debug, Eq, PartialEq)]
pub struct ProjectInspection {
    pub imports: Vec<String>,
}

#[derive(Clone, Debug)]
struct Definition {
    module_id: String,
    filename: String,
    name: String,
    canonical: String,
    mangled: String,
    params: Vec<Parameter>,
    body: String,
}

#[derive(Clone, Debug)]
struct Parameter {
    name: String,
    kind: String,
    default: Option<String>,
}

#[derive(Clone, Debug)]
enum CompilerImportKind {
    Namespace(String),
    Named(Vec<String>),
}

#[derive(Clone, Debug)]
struct CompilerImport {
    kind: CompilerImportKind,
    specifier: String,
    span: SourceSpan,
}

#[derive(Clone, Debug)]
struct ParsedFile {
    module_id: String,
    filename: String,
    source: String,
    definitions: Vec<Definition>,
    imports: Vec<CompilerImport>,
    removals: Vec<SourceSpan>,
    vars_prefix: String,
}

pub fn inspect_project_file(source: &str) -> ProjectInspection {
    let imports = scan_imports(source)
        .into_iter()
        .map(|import| import.specifier)
        .collect();
    ProjectInspection { imports }
}

pub fn compile_project(
    files: &[ProjectFile<'_>],
    resolutions: &[ImportResolution<'_>],
    target_module_id: &str,
    partial_path: &str,
) -> Result<ProjectOutput, Vec<Diagnostic>> {
    let mut diagnostics = Vec::new();
    let mut parsed = Vec::new();
    for file in files {
        match parse_file(file) {
            Ok(file) => parsed.push(file),
            Err(mut errors) => diagnostics.append(&mut errors),
        }
    }
    if !diagnostics.is_empty() {
        return Err(diagnostics);
    }

    let resolution_map: BTreeMap<_, _> = resolutions
        .iter()
        .map(|resolution| {
            (
                (
                    resolution.importer.to_owned(),
                    resolution.specifier.to_owned(),
                ),
                resolution.target.to_owned(),
            )
        })
        .collect();
    let modules: BTreeSet<_> = parsed.iter().map(|file| file.module_id.as_str()).collect();
    for file in &parsed {
        for import in &file.imports {
            let key = (file.module_id.clone(), import.specifier.clone());
            match resolution_map.get(&key) {
                Some(target) if modules.contains(target.as_str()) => {}
                Some(_) => diagnostics.push(diagnostic(
                    file,
                    import.span,
                    "injection imports must resolve to a project .xcss file",
                )),
                None => diagnostics.push(diagnostic(
                    file,
                    import.span,
                    &format!("cannot resolve injection import `{}`", import.specifier),
                )),
            }
        }
    }
    if !diagnostics.is_empty() {
        return Err(diagnostics);
    }

    let by_module: BTreeMap<_, _> = parsed
        .iter()
        .map(|file| (file.module_id.clone(), file))
        .collect();
    let mut global: BTreeMap<String, Vec<&Definition>> = BTreeMap::new();
    for file in &parsed {
        for definition in &file.definitions {
            global
                .entry(definition.canonical.clone())
                .or_default()
                .push(definition);
        }
    }

    let mut partial = String::from("// Generated by XCSS. Do not edit.\n");
    for file in &parsed {
        for definition in &file.definitions {
            let resolver = Resolver::new(file, &by_module, &global, &resolution_map)?;
            let body = rewrite_calls(&definition.body, file, &resolver, &mut diagnostics);
            let params = definition
                .params
                .iter()
                .map(|parameter| match &parameter.default {
                    Some(default) => format!("${}: {}", parameter.name, default),
                    None => format!("${}", parameter.name),
                })
                .collect::<Vec<_>>()
                .join(", ");
            let mixin = format!("@mixin {}({}) {{{}\n}}\n", definition.mangled, params, body);
            let mixin_source = format!("{}\n{mixin}", file.vars_prefix);
            match transform(
                &mixin_source,
                TransformOptions {
                    syntax: Syntax::Scss,
                    filename: Some(&definition.filename),
                    module_id: Some(&definition.module_id),
                },
            ) {
                Ok(output) => {
                    if let Some(start) = output.code.find("@mixin") {
                        partial.push_str(&output.code[start..]);
                    }
                }
                Err(mut errors) => diagnostics.append(&mut errors),
            }
        }
    }

    let Some(target) = by_module.get(target_module_id).copied() else {
        return Err(vec![plain_diagnostic(
            None,
            "target module is not present in the XCSS project registry",
        )]);
    };
    let resolver = Resolver::new(target, &by_module, &global, &resolution_map)?;
    let mut source = remove_spans(&target.source, &target.removals);
    source = rewrite_calls(&source, target, &resolver, &mut diagnostics);
    if !diagnostics.is_empty() {
        return Err(diagnostics);
    }
    let transformed = transform(
        &source,
        TransformOptions {
            syntax: Syntax::Scss,
            filename: Some(&target.filename),
            module_id: Some(&target.module_id),
        },
    )?;
    let escaped = partial_path.replace('\\', "/").replace('"', "\\\"");
    Ok(ProjectOutput {
        code: format!("@use \"{escaped}\" as *;\n{}", transformed.code),
        partial,
    })
}

struct Resolver<'a> {
    local: BTreeMap<String, &'a Definition>,
    named: BTreeMap<String, &'a Definition>,
    namespaces: BTreeMap<String, BTreeMap<String, &'a Definition>>,
    global: &'a BTreeMap<String, Vec<&'a Definition>>,
}

impl<'a> Resolver<'a> {
    fn new(
        file: &'a ParsedFile,
        modules: &BTreeMap<String, &'a ParsedFile>,
        global: &'a BTreeMap<String, Vec<&'a Definition>>,
        resolutions: &BTreeMap<(String, String), String>,
    ) -> Result<Self, Vec<Diagnostic>> {
        let local = file
            .definitions
            .iter()
            .map(|definition| (definition.canonical.clone(), definition))
            .collect();
        let mut named = BTreeMap::new();
        let mut namespaces = BTreeMap::new();
        let mut diagnostics = Vec::new();
        for import in &file.imports {
            let target_id = &resolutions[&(file.module_id.clone(), import.specifier.clone())];
            let target = modules[target_id];
            match &import.kind {
                CompilerImportKind::Namespace(namespace) => {
                    if namespaces.contains_key(namespace) {
                        diagnostics.push(diagnostic(
                            file,
                            import.span,
                            "duplicate injection namespace",
                        ));
                        continue;
                    }
                    namespaces.insert(
                        namespace.clone(),
                        target
                            .definitions
                            .iter()
                            .map(|definition| (definition.canonical.clone(), definition))
                            .collect(),
                    );
                }
                CompilerImportKind::Named(names) => {
                    for name in names {
                        let canonical = canonical(name);
                        let Some(definition) = target
                            .definitions
                            .iter()
                            .find(|definition| definition.canonical == canonical)
                        else {
                            diagnostics.push(diagnostic(
                                file,
                                import.span,
                                &format!(
                                    "injection `{name}` is not exported by `{}`",
                                    import.specifier
                                ),
                            ));
                            continue;
                        };
                        if named.insert(canonical, definition).is_some() {
                            diagnostics.push(diagnostic(
                                file,
                                import.span,
                                "conflicting named injection import",
                            ));
                        }
                    }
                }
            }
        }
        if diagnostics.is_empty() {
            Ok(Self {
                local,
                named,
                namespaces,
                global,
            })
        } else {
            Err(diagnostics)
        }
    }

    fn resolve(&self, name: &str) -> Result<&Definition, String> {
        if let Some((namespace, member)) = name.split_once('.') {
            return self
                .namespaces
                .get(namespace)
                .and_then(|entries| entries.get(&canonical(member)))
                .copied()
                .ok_or_else(|| format!("unknown injection `{name}`"));
        }
        let key = canonical(name);
        if let Some(definition) = self.local.get(&key).or_else(|| self.named.get(&key)) {
            return Ok(definition);
        }
        match self.global.get(&key).map(Vec::as_slice) {
            Some([definition]) => Ok(definition),
            Some(_) => Err(format!(
                "ambiguous injection `{name}`; import the intended definition"
            )),
            None => Err(format!("unknown injection `{name}`")),
        }
    }
}

fn parse_file(file: &ProjectFile<'_>) -> Result<ParsedFile, Vec<Diagnostic>> {
    let imports = scan_imports(file.source);
    let mut removals: Vec<_> = imports.iter().map(|import| import.span).collect();
    let mut definitions = Vec::new();
    let mut diagnostics = Vec::new();
    let bytes = file.source.as_bytes();
    let mut index = 0;
    let mut depth = 0usize;
    let mut seen = BTreeSet::new();
    while index < bytes.len() {
        if starts_comment(bytes, index) {
            index = skip_comment(bytes, index);
            continue;
        }
        if matches!(bytes[index], b'\'' | b'"') {
            index = skip_string(bytes, index);
            continue;
        }
        if bytes[index] == b'{' {
            depth += 1;
            index += 1;
            continue;
        }
        if bytes[index] == b'}' {
            depth = depth.saturating_sub(1);
            index += 1;
            continue;
        }
        if !file.source[index..].starts_with("@injection") {
            index += 1;
            continue;
        }
        let start = index;
        if depth != 0 {
            diagnostics.push(file_diagnostic(
                file,
                start,
                start + 10,
                "@injection is only allowed at the top level",
            ));
        }
        index += 10;
        index = skip_ws(bytes, index);
        let name_start = index;
        while index < bytes.len() && is_ident_byte(bytes[index]) {
            index += 1;
        }
        let name = file.source[name_start..index].to_owned();
        if name.is_empty() {
            diagnostics.push(file_diagnostic(
                file,
                start,
                index,
                "@injection requires a name",
            ));
            break;
        }
        let canonical_name = canonical(&name);
        if !seen.insert(canonical_name.clone()) {
            diagnostics.push(file_diagnostic(
                file,
                name_start,
                index,
                "duplicate injection name",
            ));
        }
        index = skip_ws(bytes, index);
        let mut params = Vec::new();
        if bytes.get(index) == Some(&b'(') {
            let Some(close) = matching(file.source, index, b'(', b')') else {
                diagnostics.push(file_diagnostic(
                    file,
                    index,
                    file.source.len(),
                    "unterminated injection parameter list",
                ));
                break;
            };
            match parse_params(&file.source[index + 1..close]) {
                Ok(value) => params = value,
                Err(message) => diagnostics.push(file_diagnostic(file, index, close + 1, &message)),
            }
            index = close + 1;
        }
        index = skip_ws(bytes, index);
        if bytes.get(index) != Some(&b'{') {
            diagnostics.push(file_diagnostic(
                file,
                start,
                index,
                "@injection requires a block",
            ));
            break;
        }
        let Some(close) = matching(file.source, index, b'{', b'}') else {
            diagnostics.push(file_diagnostic(
                file,
                index,
                file.source.len(),
                "unterminated injection block",
            ));
            break;
        };
        let hash = fnv1a64(&file.module_id.replace('\\', "/"));
        definitions.push(Definition {
            module_id: file.module_id.to_owned(),
            filename: file.filename.to_owned(),
            name: name.clone(),
            canonical: canonical_name,
            mangled: format!("xcss-{hash:016x}-{name}"),
            params,
            body: file.source[index + 1..close].to_owned(),
        });
        removals.push(SourceSpan {
            start,
            end: close + 1,
        });
        index = close + 1;
    }
    if diagnostics.is_empty() {
        Ok(ParsedFile {
            module_id: file.module_id.to_owned(),
            filename: file.filename.to_owned(),
            source: file.source.to_owned(),
            definitions,
            imports,
            removals,
            vars_prefix: vars_blocks(file.source),
        })
    } else {
        Err(diagnostics)
    }
}

fn vars_blocks(source: &str) -> String {
    let bytes = source.as_bytes();
    let mut output = String::new();
    let mut index = 0;
    let mut depth = 0usize;
    while index < bytes.len() {
        if starts_comment(bytes, index) {
            index = skip_comment(bytes, index);
            continue;
        }
        if matches!(bytes[index], b'\'' | b'"') {
            index = skip_string(bytes, index);
            continue;
        }
        if bytes[index] == b'{' {
            depth += 1;
            index += 1;
            continue;
        }
        if bytes[index] == b'}' {
            depth = depth.saturating_sub(1);
            index += 1;
            continue;
        }
        if depth == 0
            && source[index..].starts_with("@vars")
            && let Some(relative_open) = source[index..].find('{')
        {
            let open = index + relative_open;
            if let Some(close) = matching(source, open, b'{', b'}') {
                output.push_str(&source[index..=close]);
                output.push('\n');
                index = close + 1;
                continue;
            }
        }
        index += 1;
    }
    output
}

fn parse_params(source: &str) -> Result<Vec<Parameter>, String> {
    if source.trim().is_empty() {
        return Ok(Vec::new());
    }
    let mut params = Vec::new();
    let mut optional_seen = false;
    for raw in split_top_level(source, b',') {
        let raw = raw.trim();
        let Some(raw) = raw.strip_prefix('$') else {
            return Err("injection parameters must start with `$`".into());
        };
        let Some((name, rest)) = raw.split_once(':') else {
            return Err("injection parameters require a CSS type".into());
        };
        let name = name.trim();
        if name.is_empty() || !name.bytes().all(is_ident_byte) {
            return Err("invalid injection parameter name".into());
        }
        let (kind, default) = match top_level_equals(rest) {
            Some(at) => (rest[..at].trim(), Some(rest[at + 1..].trim().to_owned())),
            None => (rest.trim(), None),
        };
        if !supported_type(kind) {
            return Err(format!("unsupported injection parameter type `{kind}`"));
        }
        if let Some(default) = &default {
            if !is_dynamic(default) {
                crate::validate_explicit_vars_value(kind, default)?;
            }
            optional_seen = true;
        } else if optional_seen {
            return Err("required injection parameters cannot follow defaulted parameters".into());
        }
        params.push(Parameter {
            name: name.to_owned(),
            kind: kind.to_owned(),
            default,
        });
    }
    Ok(params)
}

fn scan_imports(source: &str) -> Vec<CompilerImport> {
    let mut imports = Vec::new();
    let bytes = source.as_bytes();
    let mut index = 0;
    while index < bytes.len() {
        if starts_comment(bytes, index) {
            index = skip_comment(bytes, index);
            continue;
        }
        if matches!(bytes[index], b'\'' | b'"') {
            index = skip_string(bytes, index);
            continue;
        }
        if !source[index..].starts_with("@import") {
            index += 1;
            continue;
        }
        let start = index;
        let Some(relative_end) = source[index..].find(';') else {
            break;
        };
        let end = index + relative_end + 1;
        let text = source[index + 7..end - 1].trim();
        let Some((binding, path)) = text.rsplit_once(" from ") else {
            index = end;
            continue;
        };
        let specifier = path.trim().trim_matches(['\'', '"']).to_owned();
        let kind = if binding.trim().starts_with('{') && binding.trim().ends_with('}') {
            CompilerImportKind::Named(
                binding.trim()[1..binding.trim().len() - 1]
                    .split(',')
                    .map(|name| name.trim().to_owned())
                    .filter(|name| !name.is_empty())
                    .collect(),
            )
        } else {
            CompilerImportKind::Namespace(binding.trim().to_owned())
        };
        imports.push(CompilerImport {
            kind,
            specifier,
            span: SourceSpan { start, end },
        });
        index = end;
    }
    imports
}

fn rewrite_calls(
    source: &str,
    file: &ParsedFile,
    resolver: &Resolver<'_>,
    diagnostics: &mut Vec<Diagnostic>,
) -> String {
    let bytes = source.as_bytes();
    let mut output = String::with_capacity(source.len());
    let mut index = 0;
    while index < bytes.len() {
        if starts_comment(bytes, index) {
            let end = skip_comment(bytes, index);
            output.push_str(&source[index..end]);
            index = end;
            continue;
        }
        if matches!(bytes[index], b'\'' | b'"') {
            let end = skip_string(bytes, index);
            output.push_str(&source[index..end]);
            index = end;
            continue;
        }
        if !source[index..].starts_with("@:") {
            let len = utf8_len(bytes[index]);
            output.push_str(&source[index..(index + len).min(bytes.len())]);
            index += len;
            continue;
        }
        let start = index;
        index += 2;
        let name_start = index;
        while index < bytes.len() && (is_ident_byte(bytes[index]) || bytes[index] == b'.') {
            index += 1;
        }
        let name = &source[name_start..index];
        let definition = match resolver.resolve(name) {
            Ok(value) => value,
            Err(message) => {
                diagnostics.push(file_diagnostic_raw(
                    &file.filename,
                    source,
                    start,
                    index,
                    &message,
                ));
                output.push_str(&source[start..index]);
                continue;
            }
        };
        index = skip_ws(bytes, index);
        let mut args = Vec::new();
        let mut args_text = String::new();
        if bytes.get(index) == Some(&b'(') {
            let Some(close) = matching(source, index, b'(', b')') else {
                diagnostics.push(file_diagnostic_raw(
                    &file.filename,
                    source,
                    index,
                    source.len(),
                    "unterminated injection call",
                ));
                break;
            };
            args_text = source[index + 1..close].to_owned();
            args = if args_text.trim().is_empty() {
                Vec::new()
            } else {
                split_top_level(&args_text, b',')
                    .into_iter()
                    .map(|value| value.trim())
                    .collect()
            };
            index = close + 1;
        }
        validate_call(definition, &args, file, source, start, index, diagnostics);
        index = skip_ws(bytes, index);
        output.push_str(&format!("@include {}({})", definition.mangled, args_text));
        if bytes.get(index) == Some(&b'{') {
            let Some(close) = matching(source, index, b'{', b'}') else {
                diagnostics.push(file_diagnostic_raw(
                    &file.filename,
                    source,
                    index,
                    source.len(),
                    "unterminated injection content block",
                ));
                break;
            };
            output.push_str(&source[index..=close]);
            index = close + 1;
        } else if bytes.get(index) == Some(&b';') {
            output.push(';');
            index += 1;
        } else {
            diagnostics.push(file_diagnostic_raw(
                &file.filename,
                source,
                start,
                index,
                "injection call requires `;` or a content block",
            ));
        }
    }
    output
}

fn validate_call(
    definition: &Definition,
    args: &[&str],
    file: &ParsedFile,
    source: &str,
    start: usize,
    end: usize,
    diagnostics: &mut Vec<Diagnostic>,
) {
    if args.len() > definition.params.len() {
        diagnostics.push(file_diagnostic_raw(
            &file.filename,
            source,
            start,
            end,
            &format!(
                "injection `{}` accepts at most {} arguments",
                definition.name,
                definition.params.len()
            ),
        ));
        return;
    }
    let mut bound = vec![false; definition.params.len()];
    let mut positional = 0usize;
    let mut named_seen = false;
    for argument in args {
        let (parameter_index, value) = if let Some(named) = argument
            .strip_prefix('$')
            .and_then(|value| value.split_once(':'))
        {
            named_seen = true;
            let key = canonical(named.0.trim());
            let Some(index) = definition
                .params
                .iter()
                .position(|parameter| canonical(&parameter.name) == key)
            else {
                diagnostics.push(file_diagnostic_raw(
                    &file.filename,
                    source,
                    start,
                    end,
                    &format!(
                        "unknown argument `${}` for injection `{}`",
                        named.0.trim(),
                        definition.name
                    ),
                ));
                continue;
            };
            (index, named.1.trim())
        } else {
            if named_seen {
                diagnostics.push(file_diagnostic_raw(
                    &file.filename,
                    source,
                    start,
                    end,
                    "positional arguments cannot follow named arguments",
                ));
            }
            let index = positional;
            positional += 1;
            (index, *argument)
        };
        if parameter_index >= bound.len() {
            continue;
        }
        if bound[parameter_index] {
            diagnostics.push(file_diagnostic_raw(
                &file.filename,
                source,
                start,
                end,
                "injection parameter is supplied more than once",
            ));
            continue;
        }
        bound[parameter_index] = true;
        let parameter = &definition.params[parameter_index];
        if is_dynamic(value) {
            continue;
        }
        if let Err(message) = validate_literal(&parameter.kind, value) {
            diagnostics.push(file_diagnostic_raw(
                &file.filename,
                source,
                start,
                end,
                &message,
            ));
        }
    }
    for (index, parameter) in definition.params.iter().enumerate() {
        if parameter.default.is_none() && !bound[index] {
            diagnostics.push(file_diagnostic_raw(
                &file.filename,
                source,
                start,
                end,
                &format!(
                    "missing required argument `${}` for injection `{}`",
                    parameter.name, definition.name
                ),
            ));
        }
    }
}

fn validate_literal(kind: &str, value: &str) -> Result<(), String> {
    let value = value.trim();
    let lower = value.to_ascii_lowercase();
    let actual = if value.ends_with('%') && value[..value.len() - 1].parse::<f64>().is_ok() {
        "percentage"
    } else if value.parse::<i64>().is_ok() {
        "integer"
    } else if value.parse::<f64>().is_ok() {
        "number"
    } else if lower.starts_with('#')
        || [
            "red",
            "blue",
            "green",
            "white",
            "black",
            "transparent",
            "currentcolor",
        ]
        .contains(&lower.as_str())
        || ["rgb(", "hsl(", "oklch(", "color("]
            .iter()
            .any(|prefix| lower.starts_with(prefix))
    {
        "color"
    } else if let Some(unit) = dimension_unit(value) {
        match unit {
            "deg" | "grad" | "rad" | "turn" => "angle",
            "s" | "ms" => "time",
            "hz" | "khz" => "frequency",
            "dpi" | "dpcm" | "dppx" | "x" => "resolution",
            "fr" => "flex",
            _ => "length",
        }
    } else if lower.starts_with("url(") {
        "url"
    } else if lower.contains("gradient(") {
        "image"
    } else {
        return Ok(());
    };
    let compatible = kind == actual
        || kind == "number" && actual == "integer"
        || kind == "length-percentage" && matches!(actual, "length" | "percentage")
        || kind == "image" && actual == "url"
        || kind.starts_with("transform-");
    if compatible {
        Ok(())
    } else {
        Err(format!(
            "injection argument of type `{actual}` does not match `{kind}`"
        ))
    }
}

