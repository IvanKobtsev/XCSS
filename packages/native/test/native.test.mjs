import assert from 'node:assert/strict'
import test from 'node:test'

import { inspect, transform } from '../index.js'

const partialPath = '/project/node_modules/.xcss/_injections.scss'

function compile(source, moduleId = 'src/a.xcss', extra = [], resolutions = []) {
  return transform(
    [{ moduleId, filename: `/project/${moduleId}`, source }, ...extra],
    resolutions,
    moduleId,
    partialPath,
  )
}

test('returns transformed code and a shared partial', () => {
  const result = compile('a { width: --size * 2; }')
  assert.equal(result.code, `@use "${partialPath}" as *;\na { width: calc(var(--size) * 2); }`)
  assert.match(result.partial, /Generated by XCSS/)
  assert.deepEqual(result.diagnostics, [])
})

test('returns structured diagnostics', () => {
  const result = compile("@use './tokens';", 'src/тема.xcss')
  assert.equal(result.code, null)
  assert.equal(result.diagnostics[0].filename, '/project/src/тема.xcss')
  assert.equal(result.diagnostics[0].line, 1)
  assert.equal(result.diagnostics[0].column, 1)
  assert.match(result.diagnostics[0].message, /XCSS import system/)
})

test('extracts and invokes typed injections with content', () => {
  const result = compile(`
    @injection panel($size: length = 1px) { border-width: $size; @content; }
    .panel { @:panel(2px) { color: red; } }
  `)
  assert.match(result.partial, /@mixin xcss-[0-9a-f]{16}-panel\(\$size: 1px\)/)
  assert.match(result.code, /@include xcss-[0-9a-f]{16}-panel\(2px\)/)
  assert.doesNotMatch(result.code, /@injection/)
})

test('inspects compiler imports', () => {
  assert.deepEqual(inspect('@import ns from "./tokens.xcss";').imports, ['./tokens.xcss'])
})
